/** Unconditional Client-form restrictions from the 9 October 2026 application export.
 * Section-level team visibility is applied separately below; other input effects remain separate.
 * Staff follows the embedded Client controls even though persistence uses standard child APIs.
 */
const hidden: Record<string, readonly string[]> = {
  Meeting_Note: ["Is_Subform"],
  Leads: ["Lead_No", "Last_Reach_Out"],
  Staff: ["Contact_Number", "Contact_Email"],
  Site: ["Site_Address_CMP", "Client_Name"],
  C4: ["Linked_CSR", "Client_Business", "ABN", "Show_BOM", "BOM_Display"],
  PO: ["C4", "Project"],
  Project_Documents: ["Project", "C4"],
  BOM: ["Project"],
  Project: [
    "Show_BOM",
    "BOM_Display",
    "Issue_Counter",
    "Business_Name",
    "ABN",
    "Batch_SN_Input",
  ],
};
export function isVisibleSubformField(subform: string, field: string) {
  return !(hidden[subform] ?? []).includes(field);
}
export function isWritableSubformField(subform: string, field: string) {
  return (
    isVisibleSubformField(subform, field) &&
    subform !== "BOM_Stack_View" &&
    !(subform === "Accounts" && field === "Username") &&
    !(subform === "Project" && field === "Project_ID")
  );
}
export function assertSubformWritable(subform: string) {
  if (subform === "BOM_Stack_View")
    throw new Error(
      "BOM Stack View is generated by the Client workflow and is read-only.",
    );
}

/** Mirror Client create/edit load branches. Null means a completed empty Staff
 * lookup; undefined means unresolved. Report permissions remain authoritative.
 */
export function isVisibleClientSubform(
  section: string,
  context?: import("./client-form-context").ClientFormContext | null,
  event: "create" | "edit" = "edit",
): boolean {
  if (["BOM", "BOM_Stack_View"].includes(section)) return false;
  if (["Project", "C4", "PO", "Project_Documents"].includes(section))
    return event === "edit";
  if (section === "Meeting_Note")
    return event === "create" || context?.teamId === "3932750000196993014";
  // The original Sales/non-Sales rules run only when staff.count() != 0.
  if (section === "Leads") return context === null || context?.sales === true;
  if (section === "Accounts")
    return context === null || context?.sales === false;
  return section === "Staff" || section === "Site";
}
